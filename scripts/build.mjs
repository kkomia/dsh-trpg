/**
 * 构建脚本：把 TypeScript 源码打成 DSH 插件可直接加载的两个文件。
 *
 * - packages/dsh-trpg-table/lib/host.js   ：Host 半边，ESM，Node 内置模块外置，workspace 源码内联。
 * - packages/dsh-trpg-table/lib/client.js ：Client 半边，CJS 打包后套上 DSH Web 的 ModuleLoader 外壳。
 *
 * 为什么自己套 ModuleLoader：DSH Web 用 window.__ModuleLoader__.load({ id, factory(require) }) 加载
 * 浏览器插件；普通 ESM/IIFE 产物无法拿到注入的 React。详见 references/ui-plugin.md。
 */
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pluginDir = join(root, 'packages', 'dsh-trpg-table');
const libDir = join(pluginDir, 'lib');
mkdirSync(libDir, { recursive: true });

const shared = {
  absWorkingDir: root,
  bundle: true,
  legalComments: 'none',
  logLevel: 'warning',
};

// Host：Node ESM
await build({
  ...shared,
  entryPoints: [join(pluginDir, 'src/host/index.ts')],
  platform: 'node',
  format: 'esm',
  target: ['node22'],
  outfile: join(libDir, 'host.js'),
});

// Client：浏览器 CJS（react 外置，由 ModuleLoader 注入）
const clientResult = await build({
  ...shared,
  entryPoints: [join(pluginDir, 'src/client/index.ts')],
  platform: 'browser',
  format: 'cjs',
  target: ['es2020'],
  external: ['react'],
  write: false,
});

const clientCode = clientResult.outputFiles[0].text;
const wrapped = `/* generated by scripts/build.mjs — do not edit by hand */
window.__ModuleLoader__.load({
  id: 'dsh-trpg-table',
  factory(require) {
    const module = { exports: {} };
    (function (module, exports, require) {
${clientCode}
    })(module, module.exports, require);
    return module.exports.createPlugin(require('react'));
  },
});
`;
writeFileSync(join(libDir, 'client.js'), wrapped, 'utf8');

console.log('[build] dsh-trpg-table → lib/host.js, lib/client.js');
